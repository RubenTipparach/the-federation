def quad():
    """A unit quad lying flat on the battle plane, facing up.

    Two callers: the grid plane, which paints itself from world position and
    ignores the texture coordinates, and the plasma ring, which is a committed
    .png and needs them. One mesh rather than two, because what differs is what
    is painted on it and not its shape (CLAUDE.md 4.1).

    UVs run 0 to 1 with V increasing toward +Z, so the image lands on the plane
    the way it would land on a table seen from above rather than mirrored."""
    o = Obj()
    n = o.normal(0, 1, 0)
    a = o.vert(-0.5, 0, -0.5)
    b = o.vert(0.5, 0, -0.5)
    c = o.vert(0.5, 0, 0.5)
    d = o.vert(-0.5, 0, 0.5)
    ta = o.uv(0.0, 0.0)
    tb = o.uv(1.0, 0.0)
    tc = o.uv(1.0, 1.0)
    td = o.uv(0.0, 1.0)
    o.tri(a, c, b, n, ta, tc, tb)
    o.tri(a, d, c, n, ta, td, tc)
    o.write("quad.obj", "Unit XZ quad, centered and UV mapped, for the grid plane and the plasma ring")


